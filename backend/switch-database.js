#!/usr/bin/env node

/**
 * Database Switcher Script
 * Quickly switch between MySQL and MongoDB
 * Usage: 
 *   node switch-database.js mysql
 *   node switch-database.js mongodb
 */

const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
const targetDB = args[0]?.toLowerCase();

const validDBs = ['mysql', 'mongodb', 'postgres', 'sqlite'];
const backendEnvPath = path.join(__dirname, '.env');

const configs = {
  mysql: {
    DB_TYPE: 'mysql',
    DB_HOST: 'localhost',
    DB_PORT: '3306',
    DB_USER: 'root',
    DB_PASSWORD: 'your_password',
    DB_NAME: 'lms',
    MONGO_URI: 'mongodb://localhost:27017/lms'
  },
  mongodb: {
    DB_TYPE: 'mongodb',
    MONGO_URI: 'mongodb://localhost:27017/lms',
    DB_HOST: 'localhost',
    DB_PORT: '3306',
    DB_USER: 'root',
    DB_PASSWORD: 'your_password',
    DB_NAME: 'lms'
  },
  postgres: {
    DB_TYPE: 'postgres',
    DB_HOST: 'localhost',
    DB_PORT: '5432',
    DB_USER: 'postgres',
    DB_PASSWORD: 'your_password',
    DB_NAME: 'lms',
    MONGO_URI: 'mongodb://localhost:27017/lms'
  },
  sqlite: {
    DB_TYPE: 'sqlite',
    DB_STORAGE: 'database.sqlite',
    DB_HOST: 'localhost',
    DB_PORT: '3306',
    DB_USER: 'root',
    DB_PASSWORD: 'your_password',
    DB_NAME: 'lms',
    MONGO_URI: 'mongodb://localhost:27017/lms'
  }
};

function printUsage() {
  console.log(`
╔════════════════════════════════════════════════╗
║       Database Switcher for E-Learning        ║
╚════════════════════════════════════════════════╝

Usage: node switch-database.js [database]

Available databases:
  mysql      - MySQL database
  mongodb    - MongoDB database
  postgres   - PostgreSQL database
  sqlite     - SQLite database

Examples:
  node switch-database.js mysql
  node switch-database.js mongodb
  node switch-database.js postgres

  `);
}

function readEnvFile() {
  try {
    if (fs.existsSync(backendEnvPath)) {
      return fs.readFileSync(backendEnvPath, 'utf8');
    }
    return '';
  } catch (error) {
    console.error('❌ Error reading .env file:', error.message);
    return '';
  }
}

function updateEnvFile(dbType) {
  const config = configs[dbType];
  let envContent = readEnvFile();

  // Parse existing env
  const envConfig = {};
  const lines = envContent.split('\n');
  lines.forEach(line => {
    const [key, ...values] = line.split('=');
    if (key && !key.startsWith('#')) {
      envConfig[key.trim()] = values.join('=').trim();
    }
  });

  // Update with new config
  const updatedConfig = { ...envConfig, ...config };

  // Include other important vars
  const otherVars = ['PORT', 'JWT_SECRET', 'JWT_EXPIRATION', 'ADMIN_EMAIL', 'ADMIN_PASSWORD', 'NODE_ENV'];
  otherVars.forEach(key => {
    if (!updatedConfig[key]) {
      switch (key) {
        case 'PORT': updatedConfig[key] = '5000'; break;
        case 'JWT_SECRET': updatedConfig[key] = 'your_jwt_secret_key'; break;
        case 'JWT_EXPIRATION': updatedConfig[key] = '3600'; break;
        case 'ADMIN_EMAIL': updatedConfig[key] = 'admin@example.com'; break;
        case 'ADMIN_PASSWORD': updatedConfig[key] = 'pass123'; break;
        case 'NODE_ENV': updatedConfig[key] = 'development'; break;
      }
    }
  });

  // Generate env file content
  let newEnvContent = `# Auto-generated by database switcher
# Generated: ${new Date().toISOString()}

# ============ Database Selection ============
DB_TYPE=${updatedConfig.DB_TYPE}

# ============ MySQL Configuration (if using MySQL) ============
DB_HOST=${updatedConfig.DB_HOST}
DB_PORT=${updatedConfig.DB_PORT}
DB_USER=${updatedConfig.DB_USER}
DB_PASSWORD=${updatedConfig.DB_PASSWORD}
DB_NAME=${updatedConfig.DB_NAME}

# ============ PostgreSQL Configuration (if using PostgreSQL) ============
# (Same as MySQL for simplicity)

# ============ SQLite Configuration (if using SQLite) ============
DB_STORAGE=${updatedConfig.DB_STORAGE || 'database.sqlite'}

# ============ MongoDB Configuration (if using MongoDB) ============
MONGO_URI=${updatedConfig.MONGO_URI}

# ============ Server & JWT Configuration ============
PORT=${updatedConfig.PORT}
JWT_SECRET=${updatedConfig.JWT_SECRET}
JWT_EXPIRATION=${updatedConfig.JWT_EXPIRATION}
ADMIN_EMAIL=${updatedConfig.ADMIN_EMAIL}
ADMIN_PASSWORD=${updatedConfig.ADMIN_PASSWORD}
NODE_ENV=${updatedConfig.NODE_ENV}
`;

  try {
    fs.writeFileSync(backendEnvPath, newEnvContent);
    return true;
  } catch (error) {
    console.error('❌ Error writing .env file:', error.message);
    return false;
  }
}

function main() {
  if (!targetDB || targetDB === '--help' || targetDB === '-h') {
    printUsage();
    return;
  }

  if (!validDBs.includes(targetDB)) {
    console.error(`\n❌ Invalid database: ${targetDB}`);
    console.error(`Valid options: ${validDBs.join(', ')}\n`);
    printUsage();
    process.exit(1);
  }

  console.log(`\n🔄 Switching to ${targetDB.toUpperCase()}...`);

  if (updateEnvFile(targetDB)) {
    console.log(`✅ Successfully switched to ${targetDB.toUpperCase()}`);
    console.log(`📝 .env file updated at: ${backendEnvPath}\n`);

    // Print next steps
    const config = configs[targetDB];
    console.log('📋 Next steps:');
    console.log(`   1. Update database credentials in .env if needed`);
    
    if (targetDB === 'mysql') {
      console.log(`   2. Ensure MySQL is running`);
      console.log(`   3. Create database: mysql -u ${config.DB_USER} -p -e "CREATE DATABASE ${config.DB_NAME};"`);
      console.log(`   4. Run migrations: mysql -u ${config.DB_USER} -p ${config.DB_NAME} < backend/config/tables.sql`);
    } else if (targetDB === 'mongodb') {
      console.log(`   2. Ensure MongoDB is running on: ${config.MONGO_URI}`);
      console.log(`   3. Collections will be created automatically by Mongoose`);
    } else if (targetDB === 'postgres') {
      console.log(`   2. Ensure PostgreSQL is running`);
      console.log(`   3. Create database: createdb -U ${config.DB_USER} ${config.DB_NAME}`);
    } else if (targetDB === 'sqlite') {
      console.log(`   2. SQLite database will be created automatically`);
    }

    console.log(`   5. Start backend: cd backend && npm start`);
    console.log(`   6. Run tests: npm run test:db\n`);
  } else {
    console.error('❌ Failed to switch database\n');
    process.exit(1);
  }
}

main();
